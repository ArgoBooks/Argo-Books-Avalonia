using ArgoBooks.Core.Enums;
using ArgoBooks.Core.Models.Common;
using ArgoBooks.Core.Models.Entities;
using ArgoBooks.Core.Models.Inventory;
using ArgoBooks.Core.Models.Transactions;
using ArgoBooks.Core.Services;
using ArgoBooks.ViewModels;
using Xunit;

namespace ArgoBooks.Tests.ViewModels;

/// <summary>
/// The Stock Levels page's Adjust Stock and Add Item modals. An adjustment moves the record's stock
/// and writes one StockAdjustment row, and a new stock record starts at its product's cost price,
/// because cost of goods sold for every later sale is read from that stock record.
/// </summary>
public class StockLevelsModalsViewModelTests : ModalViewModelTestBase
{
    private InventoryItem SeedItem(decimal inStock, decimal unitCost = 2m, decimal openingUnits = 0)
    {
        Company.Locations.Add(new Location { Id = "LOC-1", Name = "Shop" });
        Company.Products.Add(new Product { Id = "PRD-1", Name = "Widget", TrackInventory = true, CostPrice = unitCost });
        var item = new InventoryItem
        {
            Id = "INV-1", ProductId = "PRD-1", LocationId = "LOC-1",
            InStock = inStock, UnitCost = unitCost, OpeningUnits = openingUnits
        };
        Company.Inventory.Add(item);
        return item;
    }

    private static void Adjust(string type, string quantity, decimal currentStock)
    {
        var vm = new StockLevelsModalsViewModel();
        vm.OpenAdjustStockModal("INV-1", "Widget", currentStock);
        vm.AdjustmentType = type;
        vm.AdjustmentQuantity = quantity;
        vm.SaveAdjustmentCommand.Execute(null);
    }

    private static Expense PurchaseOf(decimal quantity, decimal unitPrice) => new()
    {
        Id = "PUR-1", Date = new DateTime(2026, 2, 1), OriginalCurrency = "USD",
        Total = quantity * unitPrice, Amount = quantity * unitPrice,
        LineItems = [new LineItem { ProductId = "PRD-1", Quantity = quantity, UnitPrice = unitPrice }]
    };

    private static Revenue SaleOf(decimal quantity) => new()
    {
        Id = "REV-1", Date = new DateTime(2026, 2, 5), OriginalCurrency = "USD",
        Total = quantity * 10m, Amount = quantity * 10m, PaymentStatus = RevenuePaymentStatus.Paid,
        LineItems = [new LineItem { ProductId = "PRD-1", Quantity = quantity, UnitPrice = 10m }]
    };

    /// <summary>
    /// Add puts units on top of the stock, Remove takes them off, and Set replaces the count. The
    /// ledger row must record the same movement, because the Stock Adjustments page and every later
    /// delete or edit read the stock history from those rows.
    /// </summary>
    [Theory]
    [InlineData("Add", "5", 15, AdjustmentType.Add, 5)]
    [InlineData("Remove", "4", 6, AdjustmentType.Remove, 4)]
    [InlineData("Set", "7", 7, AdjustmentType.Set, 7)]
    public void SaveAdjustment_EachType_SetsStockAndWritesAMatchingLedgerRow(
        string type, string quantity, int expectedStock, AdjustmentType expectedType, int expectedQuantity)
    {
        var item = SeedItem(inStock: 10);

        Adjust(type, quantity, 10);

        Assert.Equal((decimal)expectedStock, item.InStock);
        var row = Assert.Single(Company.StockAdjustments);
        Assert.Equal("INV-1", row.InventoryItemId);
        Assert.Equal(expectedType, row.AdjustmentType);
        Assert.Equal((decimal)expectedQuantity, row.Quantity);
        Assert.Equal(10m, row.PreviousStock);
        Assert.Equal((decimal)expectedStock, row.NewStock);
        Assert.False(row.IsAutoGenerated);
    }

    /// <summary>
    /// Undo has to put the stock and the ledger back together, and redo has to bring both back, or
    /// the stock count and its history disagree.
    /// </summary>
    [Fact]
    public void SaveAdjustment_UndoThenRedo_RestoresStockAndLedgerTogether()
    {
        var item = SeedItem(inStock: 10);
        Adjust("Remove", "4", 10);

        Undo();
        Assert.Equal(10m, item.InStock);
        Assert.Empty(Company.StockAdjustments);

        Redo();
        Assert.Equal(6m, item.InStock);
        Assert.Equal(AdjustmentType.Remove, Assert.Single(Company.StockAdjustments).AdjustmentType);
    }

    /// <summary>
    /// Removing more than is in stock must be refused, as the Stock Adjustments page refuses it.
    /// Quietly clearing the stock to zero records a different removal from the one the user typed,
    /// and the two pages would then treat the same entry differently.
    /// </summary>
    [Fact]
    public void SaveAdjustment_RemoveMoreThanInStock_IsRefusedLikeTheStockAdjustmentsPage()
    {
        var item = SeedItem(inStock: 10);

        Adjust("Remove", "25", 10);

        Assert.Equal(10m, item.InStock);
        Assert.Empty(Company.StockAdjustments);
    }

    /// <summary>
    /// Opening units are stock that was already expensed when it was bought, so a sale uses them at
    /// no cost. When all ten on hand are opening units and six are taken out by hand, only four
    /// opening units are left. A later sale must not use the six that are gone, or it sells units
    /// bought at $3 as if they cost nothing and cost of goods sold reads too low.
    /// </summary>
    [Theory]
    [InlineData("Remove", "6")]
    [InlineData("Set", "4")]
    public void SaveAdjustment_TakingOutOpeningStock_LaterSaleDoesNotUseTheRemovedOpeningUnits(string type, string quantity)
    {
        SeedItem(inStock: 10, unitCost: 2m, openingUnits: 10);
        Adjust(type, quantity, 10);

        var purchase = PurchaseOf(6, 3m);
        InventoryStockService.Apply(Company, purchase.LineItems, purchase, isPurchase: true);
        var sale = SaleOf(10);
        InventoryStockService.Apply(Company, sale.LineItems, sale, isPurchase: false);

        // Four opening units at no cost, and the six bought at $3.
        Assert.Equal(4m, sale.LineItems[0].OpeningUnitsUsed);
        Assert.Equal(18m, sale.LineItems[0].CostOfGoodsUSD);
    }

    /// <summary>
    /// Opening units can never exceed the stock on hand, so a removal takes them down with it, and
    /// undo and redo have to move them back and forth with the stock.
    /// </summary>
    [Fact]
    public void SaveAdjustment_RemoveOpeningStock_UndoAndRedoMoveTheOpeningUnitsWithTheStock()
    {
        var item = SeedItem(inStock: 10, unitCost: 2m, openingUnits: 10);
        Adjust("Remove", "6", 10);
        Assert.Equal(4m, item.InStock);
        Assert.Equal(4m, item.OpeningUnits);

        Undo();
        Assert.Equal(10m, item.InStock);
        Assert.Equal(10m, item.OpeningUnits);

        Redo();
        Assert.Equal(4m, item.InStock);
        Assert.Equal(4m, item.OpeningUnits);
    }

    private StockLevelsModalsViewModel OpenAddItem(Product product, string quantity)
    {
        var vm = new StockLevelsModalsViewModel();
        vm.OpenAddItemModal();
        vm.SelectedProduct = product;
        vm.SelectedLocation = vm.AvailableLocations.First();
        vm.AddItemQuantity = quantity;
        return vm;
    }

    private Product SeedProductAndLocation(decimal costPrice)
    {
        Company.Locations.Add(new Location { Id = "LOC-1", Name = "Shop" });
        var product = new Product { Id = "PRD-1", Name = "Widget", TrackInventory = true, CostPrice = costPrice };
        Company.Products.Add(product);
        return product;
    }

    /// <summary>
    /// A stock record made by hand starts at its product's cost price. A sale from it then carries
    /// that cost, so the profit on it is not overstated by a cost of zero.
    /// </summary>
    [Fact]
    public async Task SaveNewItem_StartsAtTheProductCostPrice_SoItsSalesCarryThatCost()
    {
        var product = SeedProductAndLocation(costPrice: 2.5m);

        await OpenAddItem(product, "12").SaveNewItemCommand.ExecuteAsync(null);

        var item = Assert.Single(Company.Inventory);
        Assert.Equal(12m, item.InStock);
        Assert.Equal(2.5m, item.UnitCost);
        Assert.False(item.IsPendingConversion);
        Assert.Equal(0m, item.OpeningUnits);

        var sale = SaleOf(4);
        InventoryStockService.Apply(Company, sale.LineItems, sale, isPurchase: false);
        Assert.Equal(10m, sale.LineItems[0].CostOfGoodsUSD);
        Assert.Equal(8m, item.InStock);
    }

    /// <summary>
    /// Undo removes the new stock record and redo brings back the same record at the same cost, so
    /// no sale can take from a record that the user undid.
    /// </summary>
    [Fact]
    public async Task SaveNewItem_UndoThenRedo_RemovesAndRestoresTheRecordWithItsCost()
    {
        var product = SeedProductAndLocation(costPrice: 2.5m);
        await OpenAddItem(product, "12").SaveNewItemCommand.ExecuteAsync(null);
        var item = Company.Inventory.Single();

        Undo();
        Assert.Empty(Company.Inventory);

        Redo();
        var restored = Assert.Single(Company.Inventory);
        Assert.Same(item, restored);
        Assert.Equal(12m, restored.InStock);
        Assert.Equal(2.5m, restored.UnitCost);
    }

    /// <summary>
    /// With no exchange rate for the company currency yet, the starting cost waits in the conversion
    /// queue rather than being stored unconverted. Undo has to take that queue entry away with the
    /// record, or the queue later writes a cost onto a record that no longer exists.
    /// </summary>
    [Fact]
    public async Task SaveNewItem_WithNoRateYet_QueuesTheCost_AndUndoTakesTheQueueEntryAway()
    {
        UseNoExchangeRates();
        Company.Settings.Localization.Currency = "CAD";
        var product = SeedProductAndLocation(costPrice: 2.5m);

        await OpenAddItem(product, "12").SaveNewItemCommand.ExecuteAsync(null);

        var item = Assert.Single(Company.Inventory);
        Assert.True(item.IsPendingConversion);
        Assert.Equal(0m, item.UnitCost);
        var queued = UsdConversion.Queued(Company, UsdConversion.KeyOf(item));
        Assert.NotNull(queued);
        Assert.Equal(2.5m, queued.Total);
        Assert.Equal("CAD", queued.OriginalCurrency);

        Undo();
        Assert.Empty(Company.Inventory);
        Assert.Null(UsdConversion.Queued(Company, UsdConversion.KeyOf(item)));

        Redo();
        Assert.NotNull(UsdConversion.Queued(Company, UsdConversion.KeyOf(item)));
    }

    /// <summary>
    /// A product can have only one stock record per location. A second one would split the count in
    /// two, and sales would take from whichever record they found first.
    /// </summary>
    [Fact]
    public async Task SaveNewItem_ForAProductAlreadyStockedAtTheLocation_IsRefused()
    {
        var item = SeedItem(inStock: 5);
        var product = Company.Products.Single();

        await OpenAddItem(product, "12").SaveNewItemCommand.ExecuteAsync(null);

        Assert.Same(item, Assert.Single(Company.Inventory));
        Assert.Equal(5m, item.InStock);
    }
}
