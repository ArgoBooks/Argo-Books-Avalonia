    /// <summary>
    /// Opens a read-only preview of an existing invoice.
    /// </summary>
    public void OpenViewInvoice(string? invoiceId)
    {
        if (string.IsNullOrEmpty(invoiceId)) return;

        var companyData = App.CompanyManager?.CompanyData;
        if (companyData == null) return;

        var invoice = companyData.Invoices.FirstOrDefault(i => i.Id == invoiceId);
        if (invoice == null) return;

        // Render with the template the invoice was created with (frozen layout the customer received),
        // falling back to the default for older invoices that don't record one.
        var template = (!string.IsNullOrEmpty(invoice.TemplateId)
                ? companyData.InvoiceTemplates.FirstOrDefault(t => t.Id == invoice.TemplateId)
                : null)
            ?? companyData.InvoiceTemplates.FirstOrDefault(t => t.IsDefault);
        if (template == null)
        {
            var defaultTemplates = InvoiceTemplateFactory.CreateDefaultTemplates();
            template = defaultTemplates.FirstOrDefault(t => t.IsDefault) ?? defaultTemplates.First();
        }

        var renderer = new InvoiceHtmlRenderer();
        // Customer-facing surfaces show the invoice in the currency it was
        // issued in, not the user's display currency. See Calculations.md §2.
        var currencySymbol = CurrencyService.GetSymbol(invoice.OriginalCurrency);
        PreviewHtml = renderer.RenderInvoice(invoice, template, companyData, currencySymbol);

        // Open modal in view-only preview mode
        ResetForm();
        IsViewOnly = true;
        IsShowingPreview = true;
        ModalTitle = "View Invoice";
        IsCreateEditModalOpen = true;
    }

    /// <summary>
    /// Opens the create modal populated with draft invoice data for continuing work.
    /// Unlike edit mode, this shows the Preview button and allows sending the invoice.
    /// </summary>
    public void ContinueDraftInvoice(InvoiceDisplayItem? item)
    {
        if (item == null) return;

        LoadCustomerOptions(includeAllOption: false);
        LoadProductOptions();
        LoadTemplateOptions();

        var invoice = App.CompanyManager?.CompanyData?.Invoices.FirstOrDefault(i => i.Id == item.Id);
        if (invoice == null) return;

        // Only allow continuing draft invoices
        if (invoice.Status != InvoiceStatus.Draft)
        {
            App.AddNotification(
                "Cannot Continue Invoice",
                "Only draft invoices can be continued.",
                NotificationType.Warning);
            return;
        }

        // Reset to a clean baseline: clears stale external-source flags
        // (IsFromRental/IsFromRevenue/IsViewOnly), unsubscribes any line items
        // left over from a previous modal session, and zeroes validation state.
        // We then overwrite the relevant fields below from the loaded invoice.
        ResetForm();

        _editingInvoiceId = invoice.Id;
        IsEditMode = true; // We're editing an existing invoice
        EditingRecurringInvoice = !string.IsNullOrEmpty(invoice.RecurringInvoiceId);
        AllowPreview = true; // Show Preview button like create mode
        ModalTitle = "Continue Invoice";
        SaveButtonText = "Preview"; // Show Preview button like create mode

        // Populate form
        SelectedCustomer = CustomerOptions.FirstOrDefault(c => c.Id == invoice.CustomerId);
        ModalIssueDate = new DateTimeOffset(invoice.IssueDate);
        ModalDueDate = new DateTimeOffset(invoice.DueDate);
        ModalStatus = invoice.Status.ToString();
        ModalNotes = invoice.Notes;
        TaxRate = invoice.TaxRate;
        TaxIsFixed = invoice.TaxIsFixed;
        SecurityDeposit = invoice.SecurityDeposit;
        ShippingAmount = invoice.ShippingAmount;
        CustomFeeLabel = invoice.CustomFeeLabel;
        CustomFeeAmount = invoice.CustomFeeAmount;
        CustomFeeIsPercent = invoice.CustomFeeIsPercent;
        DiscountAmount = invoice.DiscountAmount;
        DiscountIsPercent = invoice.DiscountIsPercent;
        SelectedCurrency = CurrencyService.GetDisplayString(
            string.IsNullOrEmpty(invoice.OriginalCurrency) ? "USD" : invoice.OriginalCurrency);

        // Restore the template this draft was created with, so the preview (and a re-save) keep it
        // instead of snapping to the default. Set it before LoadOptionsFrom so that its saved overrides
        // win over the template's defaults; IsEditMode is already true, so this won't clobber the notes.
        if (!string.IsNullOrEmpty(invoice.TemplateId))
        {
            var savedTemplate = TemplateOptions.FirstOrDefault(t => t.Id == invoice.TemplateId);
            if (savedTemplate != null)
                SelectedTemplate = savedTemplate;
        }

        // Restore this invoice's saved display overrides (falls back to the template when absent).
        LoadOptionsFrom(invoice, SelectedTemplate);

        // Populate line items, unsubscribe the ResetForm placeholder before clearing
        // so we don't leak its PropertyChanged subscription.
        foreach (var existing in LineItems)
            existing.PropertyChanged -= OnLineItemPropertyChanged;
        LineItems.Clear();
        foreach (var lineItem in invoice.LineItems)
        {
            var displayItem = new LineItemDisplayModel
            {
                SelectedProduct = ProductOptions.FirstOrDefault(p => p.Id == lineItem.ProductId),
                RentalRecordId = lineItem.RentalRecordId,
                RevenueRecordId = lineItem.RevenueRecordId,
                Description = lineItem.Description,
                Quantity = lineItem.Quantity,
                UnitPrice = lineItem.UnitPrice,

                // Carried rather than shown. The form has nowhere to display either, but
                // dropping them here is what made saving an imported invoice erase them.
                Discount = lineItem.Discount,
                TaxRate = lineItem.TaxRate,
                InvoiceCurrencyCode = SelectedCurrencyCode
            };
            displayItem.PropertyChanged += OnLineItemPropertyChanged;
            LineItems.Add(displayItem);
        }

        // Add a default line item if none exist
        if (LineItems.Count == 0)
        {
            AddLineItem();
        }

        UpdateTotals();
        HasCustomerError = false;
        ValidationMessage = string.Empty;
        HasValidationMessage = false;

        // Capture original values for change detection
        CaptureOriginalValues();

        OnPropertyChanged(nameof(CompanyName));
        OnPropertyChanged(nameof(InvoiceNumberDisplay));
        OnPropertyChanged(nameof(ProductsJson));
        OnPropertyChanged(nameof(CustomersJson));
        OnPropertyChanged(nameof(TotalsConfigJson));
        GeneratePreviewHtml();
        IsCreateEditModalOpen = true;
    }

