    /// <summary>
    /// If the user flipped "Repeat this invoice" and this invoice doesn't already have a schedule,
    /// create the recurring schedule and add it to the company data. Called from both the
    /// save-as-draft and create-and-send paths so a recurring invoice is scheduled either way.
    /// The invoice being saved stands in for every occurrence up to its own issue date, so the
    /// next one is the first date of the start date's series after it: a later start is itself
    /// the next invoice, and an earlier one does not put a draft beside the invoice just saved.
    /// </summary>
    private void CreateRecurringScheduleIfNeeded(Invoice invoice, CompanyData companyData, IdGenerator idGenerator)
    {
        if (!IsRecurring || !string.IsNullOrEmpty(invoice.RecurringInvoiceId))
            return;

        var startDate = (RecurringStartDate ?? DateTimeOffset.Now).Date;
        var schedule = new RecurringInvoice
        {
            Id = idGenerator.NextRecurringInvoiceId(),
            CustomerId = invoice.CustomerId,
            Amount = invoice.Total,
            Description = invoice.LineItems.FirstOrDefault()?.Description ?? string.Empty,
            Frequency = RecurringFrequency,
            StartDate = startDate,
            EndDate = RecurringEndDate?.Date,
            NextInvoiceDate = RecurrenceSchedule.FirstOnOrAfter(
                startDate, RecurringFrequency, startDate.Day, invoice.IssueDate.Date.AddDays(1)),
            // Inherit the terms the user set on this invoice (its issue->due span) instead of a fixed default.
            PaymentTerms = RecurringInvoiceService.FormatPaymentTerms(invoice.IssueDate, invoice.DueDate),
            Status = RecurringInvoiceStatus.Active,
            Template = RecurringInvoiceService.BuildTemplateFrom(invoice)
        };
        invoice.RecurringInvoiceId = schedule.Id;
        companyData.RecurringInvoices.Add(schedule);
    }

    [RelayCommand]
    private async Task SaveAsDraft()
    {
        // A draft goes to nobody, so nothing is required to save one. The customer and the
        // rest are checked on the send instead.
        HasCustomerError = false;
        ValidationMessage = string.Empty;
        HasValidationMessage = false;

        var companyData = App.CompanyManager?.CompanyData;
        if (companyData == null) return;

        var idGenerator = new IdGenerator(companyData);

        // If we're continuing an existing draft (opened via "Continue"), update it in place instead of
        // minting a brand-new invoice - otherwise "Save as draft" would leave a duplicate copy behind.
        var isContinuingDraft = !string.IsNullOrEmpty(_editingInvoiceId) && AllowPreview;
        var existingDraft = isContinuingDraft
            ? companyData.Invoices.FirstOrDefault(i => i.Id == _editingInvoiceId)
            : null;

        var newLineItems = LineItems.Select(i => new LineItem
        {
            ProductId = i.SelectedProduct?.Id,
            RentalRecordId = i.RentalRecordId,
            RevenueRecordId = i.RevenueRecordId,
            Description = i.Description,
            Quantity = i.Quantity ?? 0,
            UnitPrice = i.UnitPrice ?? 0,

            // Carried through, as on the send path. Zero on anything created here.
            TaxRate = i.TaxRate,
            Discount = i.Discount
        }).ToList();

        Invoice invoice;
        if (existingDraft != null)
        {
            invoice = existingDraft;
            invoice.CustomerId = SelectedCustomer?.Id ?? string.Empty;
            invoice.IssueDate = ModalIssueDate?.DateTime ?? DateTime.Now;
            invoice.DueDate = ModalDueDate?.DateTime ?? DateTime.Now.AddMonths(1);
            invoice.TaxRate = TaxRate;
            invoice.TaxIsFixed = TaxIsFixed;
            invoice.SecurityDeposit = SecurityDeposit;
            invoice.ShippingAmount = ShippingAmount;
            invoice.CustomFeeLabel = CustomFeeLabel;
            invoice.CustomFeeAmount = CustomFeeAmount;
            invoice.CustomFeeIsPercent = CustomFeeIsPercent;
            invoice.DiscountAmount = DiscountAmount;
            invoice.DiscountIsPercent = DiscountIsPercent;
            invoice.Notes = ModalNotes;
            invoice.UpdatedAt = DateTime.UtcNow;
            invoice.LineItems = newLineItems;
        }
        else
        {
            invoice = new Invoice
            {
                Id = idGenerator.NextInvoiceId(),
                InvoiceNumber = idGenerator.NextInvoiceNumber(),
                CustomerId = SelectedCustomer?.Id ?? string.Empty,
                IssueDate = ModalIssueDate?.DateTime ?? DateTime.Now,
                DueDate = ModalDueDate?.DateTime ?? DateTime.Now.AddMonths(1),
                TaxRate = TaxRate,
                TaxIsFixed = TaxIsFixed,
                SecurityDeposit = SecurityDeposit,
                ShippingAmount = ShippingAmount,
                CustomFeeLabel = CustomFeeLabel,
                CustomFeeAmount = CustomFeeAmount,
                CustomFeeIsPercent = CustomFeeIsPercent,
                DiscountAmount = DiscountAmount,
                DiscountIsPercent = DiscountIsPercent,
                Notes = ModalNotes,
                Status = InvoiceStatus.Draft,
                CreatedAt = DateTime.UtcNow,
                UpdatedAt = DateTime.UtcNow,
                LineItems = newLineItems
            };
        }

        ApplyOptionsTo(invoice);

        // Compute and store invoice-level totals (Subtotal / TaxAmount /
        // Total). Payment-derived fields are set by InvoiceTotalsService
        // below, see docs/Calculations.md §5.
        invoice.Subtotal = Subtotal;
        invoice.TaxAmount = TaxAmount;
        invoice.Total = Total;

        // Set currency fields for multi-currency support
        invoice.OriginalCurrency = SelectedCurrencyCode;
        await ApplyUsdTotalAsync(companyData, invoice);

        InvoiceTotalsService.Recalculate(invoice, companyData.Payments);

        // Add the invoice (new only - a continued draft is already in the collection) and link to rentals.
        if (existingDraft == null)
        {
            companyData.Invoices.Add(invoice);
            _ = App.TelemetryManager?.TrackFeatureAsync(FeatureName.InvoiceCreated);
        }
        LinkInvoiceToRentals(invoice, companyData);

        CreateRecurringScheduleIfNeeded(invoice, companyData, idGenerator);

        // Editing an already-published invoice changes what the customer owes,
        // so the portal needs the new total or it would chase the old one. A
        // no-op for invoices that were never published, and for brand-new ones
        // the publish path sends the full record anyway.
        App.PortalBalanceSyncService?.Queue(invoice.Id);

        LastSavedInvoiceId = invoice.Id;
        InvoiceSaved?.Invoke(this, EventArgs.Empty);
        CloseCreateEditModal();

        // Auto-save immediately (suppress "Saved" label since this is an automatic save)
        if (App.CompanyManager != null)
        {
            App.SuppressNextSavedFeedback();
            try { await App.CompanyManager.SaveCompanyAsync(); }
            catch (Exception ex) { System.Diagnostics.Debug.WriteLine($"Save failed: {ex.Message}"); }
        }
    }

    /// <summary>
    /// Links an invoice to any rental records referenced by its line items.
    /// </summary>
    private static void LinkInvoiceToRentals(Invoice invoice, CompanyData companyData)
    {
        foreach (var rentalId in invoice.LineItems
                     .Where(li => !string.IsNullOrEmpty(li.RentalRecordId))
                     .Select(li => li.RentalRecordId!)
                     .Distinct())
        {
            var rental = companyData.Rentals.FirstOrDefault(r => r.Id == rentalId);
            if (rental != null && !rental.InvoiceIds.Contains(invoice.Id))
                rental.InvoiceIds.Add(invoice.Id);
        }
    }

    /// <summary>
    /// Unlinks an invoice from any rental records referenced by its line items.
    /// </summary>
    private static void UnlinkInvoiceFromRentals(Invoice invoice, CompanyData companyData)
    {
        foreach (var rentalId in invoice.LineItems
                     .Where(li => !string.IsNullOrEmpty(li.RentalRecordId))
                     .Select(li => li.RentalRecordId!)
                     .Distinct())
        {
            var rental = companyData.Rentals.FirstOrDefault(r => r.Id == rentalId);
            rental?.InvoiceIds.Remove(invoice.Id);
        }
    }

    /// <summary>
    /// Links an invoice to any revenue records referenced by its line items.
    /// </summary>
    private static void LinkInvoiceToRevenue(Invoice invoice, CompanyData companyData)
    {
        foreach (var revenueId in invoice.LineItems
                     .Where(li => !string.IsNullOrEmpty(li.RevenueRecordId))
                     .Select(li => li.RevenueRecordId!)
                     .Distinct())
        {
            var revenue = companyData.Revenues.FirstOrDefault(r => r.Id == revenueId);
            if (revenue != null)
                revenue.InvoiceId = invoice.Id;
        }
    }

    /// <summary>
    /// The invoice's USD total at its issue date's rate, or pending when there is none (future
    /// dated, offline, or no rate service) so the conversion queue prices it later. Keeping the
    /// previous figure, 0 or another date's rate, dropped the invoice out of Outstanding Invoices
    /// for good and priced its online payments at nothing (docs/Calculations.md Rule 3a).
    /// </summary>
    private static async Task ApplyUsdTotalAsync(CompanyData companyData, Invoice invoice)
    {
        companyData.PendingConversions.RemoveAll(p => p.TransactionId == invoice.Id);

        if (string.Equals(invoice.OriginalCurrency, "USD", StringComparison.OrdinalIgnoreCase))
        {
            invoice.TotalUSD = invoice.Total;
            invoice.IsPendingConversion = false;
        }
        else
        {
            var rate = ExchangeRateService.Instance is { } exchangeService
                ? await exchangeService.GetExchangeRateAsync(invoice.OriginalCurrency, "USD", invoice.IssueDate)
                : 0m;

            // USD base stored full-precision (no 2dp round); display rounds. See Calculations.md Rule 3.
            invoice.TotalUSD = rate > 0 ? invoice.Total * rate : 0m;
            invoice.IsPendingConversion = rate <= 0;

            if (invoice.IsPendingConversion)
            {
                companyData.PendingConversions.Add(new PendingConversion
                {
                    TransactionId = invoice.Id,
                    TransactionType = "Invoice",
                    OriginalCurrency = invoice.OriginalCurrency,
                    TransactionDate = invoice.IssueDate,
                    Total = invoice.Total,
                    Balance = Math.Max(0, invoice.Total - invoice.AmountPaid)
                });
            }
        }

        _ = PendingConversionService.Instance?.MirrorAsync(companyData, [invoice.Id]);
    }

    /// <summary>
    /// Creates a Revenue transaction automatically from a sent invoice.
    /// This handles the "Invoice → Revenue" path so the revenue table stays
    /// the single source of truth for all financial data.
    /// </summary>
    internal static void CreateRevenueFromInvoice(Invoice invoice, CompanyData companyData)
    {
        var revenueId = new Core.Data.IdGenerator(companyData).NextRevenueId(invoice.IssueDate);

        var description = invoice.LineItems.Count switch
        {
            0 => $"Invoice {invoice.InvoiceNumber}",
            1 => invoice.LineItems[0].Description,
            _ => $"{invoice.LineItems[0].Description} (+{invoice.LineItems.Count - 1} more)"
        };

        var totalQuantity = invoice.LineItems.Sum(li => li.Quantity);
        if (totalQuantity == 0) totalQuantity = 1;

        // Calculate the effective fee and discount as flat amounts
        var feeAmount = invoice.CustomFeeIsPercent
            ? invoice.Subtotal * (invoice.CustomFeeAmount / 100m)
            : invoice.CustomFeeAmount;
        var discountAmount = invoice.DiscountIsPercent
            ? invoice.Subtotal * (invoice.DiscountAmount / 100m)
            : invoice.DiscountAmount;

        // The deposit is held for the customer, not earned, so it stays out of the revenue
        // (docs/Calculations.md §4). A deposit kept when the rental comes back is added then.
        var total = invoice.Total - invoice.SecurityDeposit;

        var revenue = new Revenue
        {
            Id = revenueId,
            Date = invoice.IssueDate,
            CustomerId = invoice.CustomerId,
            Description = description,
            LineItems = invoice.LineItems.Select(li => new LineItem
            {
                ProductId = li.ProductId,
                Description = li.Description,
                Quantity = li.Quantity,
                UnitPrice = li.UnitPrice,
                TaxRate = li.TaxRate,
                Discount = li.Discount
            }).ToList(),
            Quantity = totalQuantity,
            UnitPrice = totalQuantity > 0 ? Math.Round(invoice.Subtotal / totalQuantity, 2) : 0,
            Subtotal = invoice.Subtotal,
            Amount = invoice.Subtotal,
            TaxRate = invoice.TaxRate,
            TaxAmount = invoice.TaxAmount,
            Fee = feeAmount + invoice.ShippingAmount,
            Discount = discountAmount,
            Total = total,
            PaymentMethod = PaymentMethod.Other,
            PaymentStatus = RevenuePaymentStatus.Unpaid,
            Notes = $"Auto-created from invoice {invoice.InvoiceNumber}",
            InvoiceId = invoice.Id,
            ReferenceNumber = invoice.InvoiceNumber,
            CreatedAt = DateTime.UtcNow,
            UpdatedAt = DateTime.UtcNow,
            // Currency fields: use EffectiveTotalUSD to avoid mixing currencies
            // (returns 0 for pending-conversion invoices, correct USD for others)
            OriginalCurrency = invoice.OriginalCurrency,
            // USD base fields stored full-precision (no 2dp round) so they stay consistent with the
            // unrounded TotalUSD above; display rounds at the boundary. See docs/Calculations.md Rule 3.
            TotalUSD = invoice.Total > 0 ? invoice.EffectiveTotalUSD * total / invoice.Total : 0,
            TaxAmountUSD = invoice.EffectiveTotalUSD > 0 && invoice.Total > 0
                ? invoice.TaxAmount * (invoice.EffectiveTotalUSD / invoice.Total)
                : string.Equals(invoice.OriginalCurrency, "USD", StringComparison.OrdinalIgnoreCase) ? invoice.TaxAmount : 0,
            FeeUSD = invoice.EffectiveTotalUSD > 0 && invoice.Total > 0
                ? (feeAmount + invoice.ShippingAmount) * (invoice.EffectiveTotalUSD / invoice.Total)
                : string.Equals(invoice.OriginalCurrency, "USD", StringComparison.OrdinalIgnoreCase) ? feeAmount + invoice.ShippingAmount : 0,
            DiscountUSD = invoice.EffectiveTotalUSD > 0 && invoice.Total > 0
                ? discountAmount * (invoice.EffectiveTotalUSD / invoice.Total)
                : string.Equals(invoice.OriginalCurrency, "USD", StringComparison.OrdinalIgnoreCase) ? discountAmount : 0,

            // An invoice still waiting for its rate hands the wait on to its revenue, which the
            // queue then converts from the same amounts. Otherwise the revenue counted as 0 for good.
            IsPendingConversion = invoice.IsPendingConversion
        };

        companyData.Revenues.Add(revenue);

        if (revenue.IsPendingConversion)
        {
            var pendingEntry = new PendingConversion
            {
                TransactionId = revenue.Id,
                TransactionType = "Revenue",
                OriginalCurrency = revenue.OriginalCurrency,
                TransactionDate = revenue.Date,
                Total = revenue.Total,
                TaxAmount = revenue.TaxAmount,
                ShippingCost = revenue.ShippingCost,
                Discount = revenue.Discount,
                Fee = revenue.Fee,
                UnitPrice = revenue.UnitPrice
            };
            companyData.PendingConversions.RemoveAll(p => p.TransactionId == revenue.Id);
            companyData.PendingConversions.Add(pendingEntry);
            _ = PendingConversionService.Instance?.AddPendingConversionAsync(pendingEntry);
        }
    }

    /// <summary>
    /// Removes the auto-created Revenue for an invoice (if any).
    /// Only removes revenues that were auto-generated (i.e., not referenced by line items).
    /// User-created revenues that were linked via "Create Invoice" are only unlinked, not deleted.
    /// </summary>
    private static void RemoveAutoCreatedRevenue(Invoice invoice, CompanyData companyData)
    {
        // Find revenues linked to this invoice
        var linkedRevenues = companyData.Revenues
            .Where(r => r.InvoiceId == invoice.Id)
            .ToList();

        // Revenue IDs that came from the user (referenced by line items), just unlink these
        var userCreatedRevenueIds = invoice.LineItems
            .Where(li => !string.IsNullOrEmpty(li.RevenueRecordId))
            .Select(li => li.RevenueRecordId!)
            .ToHashSet();

        foreach (var revenue in linkedRevenues)
        {
            if (userCreatedRevenueIds.Contains(revenue.Id))
            {
                // User created this revenue first, then generated the invoice → just unlink
                revenue.InvoiceId = null;
            }
            else
            {
                // Auto-created from the invoice → remove entirely
                companyData.Revenues.Remove(revenue);
            }
        }
    }

