    [RelayCommand]
    private async Task CreateAndSendInvoice()
    {
        var companyData = App.CompanyManager?.CompanyData;
        if (companyData == null) return;

        // Start each attempt from a clean slate so a banner from a previous attempt never lingers.
        HasSendError = false;
        SendErrorMessage = string.Empty;

        // Require a customer and a positive total before anything else (including the server usage
        // check). Both are hard requirements for a sendable invoice.
        if (SelectedCustomer == null || string.IsNullOrEmpty(SelectedCustomer.Id))
        {
            await ShowSendErrorAsync("Please select a customer.".Translate());
            return;
        }

        // Every line item must reference a real product (rental/revenue-derived lines are exempt).
        if (!IsFromExternalSource && LineItems.Any(li =>
                li.SelectedProduct == null
                && string.IsNullOrEmpty(li.RentalRecordId)
                && string.IsNullOrEmpty(li.RevenueRecordId)))
        {
            await ShowSendErrorAsync("Please select a product for all line items.".Translate());
            return;
        }

        if (Total <= 0)
        {
            await ShowSendErrorAsync("Cannot send an invoice for {0}0 or less.".TranslateFormat(CurrencyService.CurrentSymbol));
            return;
        }

        // A recurring schedule that has already ended can never generate an invoice.
        if (IsRecurring && RecurringEndDate is { } recurringEnd && recurringEnd.Date < DateTime.Today)
        {
            await ShowSendErrorAsync("The recurring end date is in the past. Choose a future end date or clear it.".Translate());
            return;
        }

        // Confirm before sending: this emails the customer and can't be undone. Verify the recipient
        // has an email up front so the confirmation can show exactly where it's going.
        var recipient = companyData.GetCustomer(SelectedCustomer.Id);
        if (recipient == null || string.IsNullOrWhiteSpace(recipient.Email))
        {
            await ShowSendErrorAsync("Customer does not have an email address.".Translate());
            return;
        }

        if (!await ConfirmSendAsync(recipient.Name, recipient.Email, Total))
        {
            return;
        }

        // Enforce free-tier invoice send limit via server
        if (!HasPremium)
        {
            var usageService = App.InvoiceUsageService;
            if (usageService != null)
            {
                var usage = await usageService.CheckUsageAsync();
                if (!usage.CanSend)
                {
                    // A failed check (offline / server unreachable) reports an ErrorMessage
                    // rather than a real limit. Show that inline instead of falsely claiming
                    // the monthly send limit was reached.
                    if (!usage.Success && !string.IsNullOrEmpty(usage.ErrorMessage))
                    {
                        await ShowSendErrorAsync(usage.ErrorMessage);
                        return;
                    }

                    var limit = usage.MonthlyLimit > 0 ? usage.MonthlyLimit : FreePlanLimits.InvoiceMonthly;
                    await UpgradePromptHelper.ShowInvoiceLimitPromptAsync(limit);
                    return;
                }
            }
        }

        // Validate that we have a template selected
        if (SelectedTemplate == null)
        {
            await ShowSendErrorAsync("Please select an invoice template.".Translate());
            return;
        }

        // Check if email API is configured (only required when portal is NOT configured,
        // since the portal server handles email delivery via sendEmail: true)
        if (!PortalSettings.IsConfigured)
        {
            await ShowSendErrorAsync("Sending invoice emails requires portal access. Please register your company first.".Translate());
            return;
        }

        // Get the customer for email
        var customer = companyData.GetCustomer(SelectedCustomer!.Id!);
        if (customer == null || string.IsNullOrWhiteSpace(customer.Email))
        {
            await ShowSendErrorAsync("Customer does not have an email address.".Translate());
            return;
        }

        // From here down: the user is committed to sending. Flip IsSending so
        // the modal swaps the preview + footer for a centered spinner. The
        // 1-2 second silent gap was confusing because nothing visibly happened
        // after the click.
        IsSending = true;
        try
        {
            await CreateAndSendInvoiceCore();
        }
        finally
        {
            IsSending = false;
        }
    }

    private async Task CreateAndSendInvoiceCore()
    {
        var companyData = App.CompanyManager?.CompanyData;
        if (companyData == null) return;

        var customer = companyData.GetCustomer(SelectedCustomer!.Id!);
        if (customer == null) return;

        // The outer CreateAndSendInvoice already guards on SelectedTemplate
        // being non-null, but the compiler can't see across method boundaries,
        // re-assert here so the SendInvoiceAsync call site doesn't warn.
        var selectedTemplate = SelectedTemplate;
        if (selectedTemplate == null) return;

        // Check if we're continuing a draft invoice or creating a new one
        var isContinuingDraft = !string.IsNullOrEmpty(_editingInvoiceId) && AllowPreview;
        Invoice invoice;
        Invoice? existingDraft;
        Action? restoreDraft = null;
        int? takenInvoiceCounter = null;

        if (isContinuingDraft)
        {
            // Find the existing draft invoice
            existingDraft = companyData.Invoices.FirstOrDefault(i => i.Id == _editingInvoiceId);
            if (existingDraft == null)
            {
                await ShowSendErrorAsync("Could not find the draft invoice.".Translate());
                return;
            }

            // A failed send puts the draft back, so discarding afterwards drops the edits rather
            // than leaving them in the draft for the next save to keep.
            restoreDraft = CaptureDraft(existingDraft, companyData);

            // Update the existing invoice
            invoice = existingDraft;
            invoice.CustomerId = SelectedCustomer!.Id!;
            invoice.IssueDate = ModalIssueDate?.DateTime ?? DateTime.Now;
            invoice.DueDate = ModalDueDate?.DateTime ?? DateTime.Now.AddMonths(1);
            invoice.TaxRate = TaxRate;
            invoice.TaxIsFixed = TaxIsFixed;
            invoice.SecurityDeposit = SecurityDeposit;
            invoice.ShippingAmount = ShippingAmount;
            invoice.CustomFeeLabel = CustomFeeLabel;
            invoice.CustomFeeAmount = CustomFeeAmount;
            invoice.CustomFeeIsPercent = CustomFeeIsPercent;
            invoice.DiscountAmount = DiscountAmount;
            invoice.DiscountIsPercent = DiscountIsPercent;
            invoice.Notes = ModalNotes;
            // Leave the status as Draft during the send attempt; it's set to Sent only after publish/email
            // succeeds (below). Flipping it to Pending here left the draft stuck and un-continuable if the
            // send then failed (ContinueDraftInvoice only accepts Draft).
            invoice.UpdatedAt = DateTime.UtcNow;
            invoice.LineItems = LineItems.Select(i => new LineItem
            {
                ProductId = i.SelectedProduct?.Id,
                RentalRecordId = i.RentalRecordId,
                RevenueRecordId = i.RevenueRecordId,
                Description = i.Description,
                Quantity = i.Quantity ?? 0,
                UnitPrice = i.UnitPrice ?? 0,

                // Carried through as on a new invoice. An imported draft's lines can hold a
                // discount, and dropping it here billed more than the total the user confirmed.
                TaxRate = i.TaxRate,
                Discount = i.Discount
            }).ToList();
        }
        else
        {
            string invoiceId, invoiceNumber;
            if (_unansweredSend is { } unanswered && unanswered.CustomerId == SelectedCustomer!.Id)
            {
                (invoiceId, invoiceNumber, _) = unanswered;
            }
            else
            {
                // Generate new invoice ID using IdGenerator
                var idGenerator = new IdGenerator(companyData);
                invoiceId = idGenerator.NextInvoiceId();
                invoiceNumber = idGenerator.NextInvoiceNumber();
                takenInvoiceCounter = companyData.IdCounters.Invoice;
            }

            invoice = new Invoice
            {
                Id = invoiceId,
                InvoiceNumber = invoiceNumber,
                CustomerId = SelectedCustomer!.Id!,
                IssueDate = ModalIssueDate?.DateTime ?? DateTime.Now,
                DueDate = ModalDueDate?.DateTime ?? DateTime.Now.AddMonths(1),
                TaxRate = TaxRate,
                TaxIsFixed = TaxIsFixed,
                SecurityDeposit = SecurityDeposit,
                ShippingAmount = ShippingAmount,
                CustomFeeLabel = CustomFeeLabel,
                CustomFeeAmount = CustomFeeAmount,
                CustomFeeIsPercent = CustomFeeIsPercent,
                DiscountAmount = DiscountAmount,
                DiscountIsPercent = DiscountIsPercent,
                Notes = ModalNotes,
                Status = InvoiceStatus.Pending,
                CreatedAt = DateTime.UtcNow,
                UpdatedAt = DateTime.UtcNow,
                LineItems = LineItems.Select(i => new LineItem
                {
                    ProductId = i.SelectedProduct?.Id,
                    RentalRecordId = i.RentalRecordId,
                    RevenueRecordId = i.RevenueRecordId,
                    Description = i.Description,
                    Quantity = i.Quantity ?? 0,
                    UnitPrice = i.UnitPrice ?? 0,

                    // Written back rather than zeroed. Both are zero on anything this form
                    // created; an imported line can carry them, and hard-coding zero here
                    // silently discarded whatever the sheet supplied.
                    TaxRate = i.TaxRate,
                    Discount = i.Discount
                }).ToList()
            };
        }

        ApplyOptionsTo(invoice);

        // Calculate invoice totals (Subtotal / TaxAmount / Total, these are
        // invoice-level math, not Payment-derived).
        invoice.Subtotal = InvoiceMath.Subtotal(invoice.LineItems);
        var feeCalc = InvoiceMath.CustomFee(invoice.Subtotal, invoice.CustomFeeAmount, invoice.CustomFeeIsPercent);
        var discCalc = InvoiceMath.Discount(invoice.Subtotal, invoice.DiscountAmount, invoice.DiscountIsPercent);
        // Tax applies to the subtotal AFTER discount and the taxable fee plus shipping (docs/Calculations.md §4).
        var taxableBase = InvoiceMath.TaxableBase(invoice.Subtotal, discCalc, feeCalc, invoice.ShippingAmount);
        invoice.TaxAmount = InvoiceMath.Tax(taxableBase, invoice.TaxRate, invoice.TaxIsFixed);
        invoice.Total = InvoiceMath.Total(taxableBase, invoice.TaxAmount, invoice.SecurityDeposit);

        // Set currency fields for multi-currency support
        invoice.OriginalCurrency = SelectedCurrencyCode;
        await ApplyUsdTotalAsync(companyData, invoice);

        // Payment-derived totals (AmountPaid / Balance / BalanceUSD) come
        // from InvoiceTotalsService so the rule "stored totals always match
        // the Payment list" is preserved. See docs/Calculations.md §5.
        InvoiceTotalsService.Recalculate(invoice, companyData.Payments);

        // Undoes what this attempt changed and says why it failed. The number goes back only when the
        // portal can't hold it: reusing one it published would put another invoice behind the link
        // that customer was emailed.
        async Task SendFailedAsync(string message, bool mayHavePublished)
        {
            restoreDraft?.Invoke();
            if (!isContinuingDraft)
            {
                if (mayHavePublished)
                    _unansweredSend = (invoice.Id, invoice.InvoiceNumber, invoice.CustomerId);
                else if (takenInvoiceCounter is { } taken && companyData.IdCounters.Invoice == taken)
                    companyData.IdCounters.Invoice = taken - 1;
            }

            await ShowSendErrorAsync(message);
        }

        // Publish and send: portal handles both publishing and email delivery via sendEmail: true.
        // When portal is not configured, fall back to desktop email sending.
        if (PortalSettings.IsConfigured)
        {
            try
            {
                var portalService = App.PaymentPortalService;
                if (portalService != null)
                {
                    // Portal publishes / customer-facing flow uses the
                    // invoice's issued currency, not user display currency.
                    var currencySymbol = CurrencyService.GetSymbol(invoice.OriginalCurrency);
                    var publishResponse = await portalService.PublishInvoiceAsync(
                        invoice, companyData, SelectedTemplate, currencySymbol);
                    if (publishResponse.Success)
                    {
                        invoice.History.Add(new InvoiceHistoryEntry
                        {
                            Action = "Published to Portal",
                            Details = "Invoice published to online payment portal",
                            Timestamp = DateTime.UtcNow
                        });

                        // Update local provider state from the server's response so the
                        // desktop app stays in sync with which methods are available.
                        if (publishResponse.PaymentMethods != null)
                        {
                            PaymentProviderService.UpdateFromPaymentMethods(publishResponse.PaymentMethods);
                        }
                    }
                    else
                    {
                        var detail = !string.IsNullOrEmpty(publishResponse.Message)
                            ? publishResponse.Message
                            : "The payment portal did not return a payment link.";
                        await SendFailedAsync(
                            $"{"Failed to publish invoice to payment portal:".Translate()} {detail}",
                            publishResponse.MayHavePublished);
                        return;
                    }
                }
            }
            catch (Exception ex)
            {
                await SendFailedAsync(
                    $"{"Failed to publish invoice to payment portal:".Translate()} {ex.Message}",
                    mayHavePublished: true);
                return;
            }
        }
        else
        {
            // No portal configured - send email directly from the desktop app
            try
            {
                var emailService = new InvoiceEmailService();
                var emailSettings = companyData.Settings.InvoiceEmail;
                // Email goes to the customer in the invoice's issued currency.
                var currencySymbol = CurrencyService.GetSymbol(invoice.OriginalCurrency);

                var response = await emailService.SendInvoiceAsync(
                    invoice,
                    selectedTemplate,
                    companyData,
                    emailSettings,
                    currencySymbol);

                if (!response.Success)
                {
                    await SendFailedAsync(response.Message, mayHavePublished: false);
                    return;
                }
            }
            catch (Exception ex)
            {
                await SendFailedAsync($"{"Failed to send invoice:".Translate()} {ex.Message}", mayHavePublished: true);
                return;
            }
        }

        _unansweredSend = null;
        invoice.Status = InvoiceStatus.Sent;
        _ = App.TelemetryManager?.TrackFeatureAsync(FeatureName.InvoiceSent);
        invoice.History.Add(new InvoiceHistoryEntry
        {
            Action = "Sent",
            Details = $"Invoice sent to {customer.Email}",
            Timestamp = DateTime.UtcNow
        });

        if (!isContinuingDraft)
        {
            // Add the new invoice to the collection and link to rentals/revenue
            companyData.Invoices.Add(invoice);
            _ = App.TelemetryManager?.TrackFeatureAsync(FeatureName.InvoiceCreated);
            LinkInvoiceToRentals(invoice, companyData);
            LinkInvoiceToRevenue(invoice, companyData);
        }
        else
        {
            // Draft is being sent - link to any revenue/rental records referenced by line items
            LinkInvoiceToRentals(invoice, companyData);
            LinkInvoiceToRevenue(invoice, companyData);
        }

        // If "Repeat this invoice" was set, create the recurring schedule here too.
        // The helper no-ops if it isn't recurring or a schedule already exists (e.g. a
        // recurring draft that was scheduled on save and is now being sent).
        CreateRecurringScheduleIfNeeded(invoice, companyData, new IdGenerator(companyData));

        // Auto-create a Revenue transaction if this invoice isn't already linked to one.
        // Path A (Revenue → Invoice): revenue already exists, LinkInvoiceToRevenue linked it above.
        // Path B (Invoice → Revenue): no revenue exists yet, so create one automatically.
        var hasLinkedRevenue = companyData.Revenues.Any(r => r.InvoiceId == invoice.Id);
        if (!hasLinkedRevenue)
        {
            CreateRevenueFromInvoice(invoice, companyData);
        }

        // Increment server-side usage count (fire-and-forget, non-blocking)
        if (!HasPremium)
        {
            _ = App.InvoiceUsageService?.IncrementUsageAsync();
        }

        LastSavedInvoiceId = invoice.Id;
        InvoiceSaved?.Invoke(this, EventArgs.Empty);

        // Auto-save immediately so the asterisk doesn't linger
        if (App.CompanyManager != null)
        {
            App.SuppressNextSavedFeedback();
            try { await App.CompanyManager.SaveCompanyAsync(); }
            catch (Exception ex) { System.Diagnostics.Debug.WriteLine($"Save failed: {ex.Message}"); }
        }

        // Show success animation instead of closing immediately
        SuccessTitle = "Invoice Sent!".Translate();
        SuccessMessage = "Your invoice has been sent to {0} at {1}".TranslateFormat(customer.Name, customer.Email);
        IsShowingPreview = false;
        IsShowingSuccess = true;
    }

    /// <summary>
    /// Returns an action that puts <paramref name="draft"/> back as it is now, with its entries in the
    /// conversion queue. Every settable property is copied so nothing a send writes is missed; the send
    /// replaces the line item list rather than editing it, so holding the old list is enough.
    /// </summary>
    private static Action CaptureDraft(Invoice draft, CompanyData companyData)
    {
        var properties = typeof(Invoice).GetProperties().Where(p => p.CanWrite).ToArray();
        var values = properties.Select(p => p.GetValue(draft)).ToArray();
        var conversions = companyData.PendingConversions.Where(p => p.TransactionId == draft.Id).ToList();

        return () =>
        {
            for (var i = 0; i < properties.Length; i++)
                properties[i].SetValue(draft, values[i]);
            companyData.PendingConversions.RemoveAll(p => p.TransactionId == draft.Id);
            companyData.PendingConversions.AddRange(conversions);
            _ = PendingConversionService.Instance?.MirrorAsync(companyData, [draft.Id]);
        };
    }

    private string PeekNextInvoiceNumber()
    {
        var companyData = App.CompanyManager?.CompanyData;
        if (companyData == null)
            return $"#INV-{DateTime.Now:yyyy}-001";

        // If editing a draft, use its existing number
        if (!string.IsNullOrEmpty(_editingInvoiceId))
        {
            var draft = companyData.Invoices.FirstOrDefault(i => i.Id == _editingInvoiceId);
            if (draft != null)
                return draft.InvoiceNumber;
        }

        if (_unansweredSend is { } unanswered && unanswered.CustomerId == SelectedCustomer?.Id)
            return unanswered.Number;

        var idGenerator = new IdGenerator(companyData);
        return idGenerator.PeekNextInvoice().Number;
    }

